"""Refute the baseline's false alarms by execution.

The baseline does not merely guess wrong on sound environments; it gives a
specific, checkable reason. On `t11_is_palindrome` it wrote "a solution that
always returns True could pass the verifier." That is a concrete claim about a
concrete program, and it is false: `return True` fails the assertion
`not is_palindrome("hello")`.

This script pairs each false alarm with the deterministic exploit the baseline
described, runs it, and shows the result. It is the cleanest demonstration of
the project's thesis: reading produces plausible reasoning, executing produces
facts.

Usage:
    python3 evaluation/refutations.py            # print markdown
    python3 evaluation/refutations.py --write    # write evaluation/refutations.md
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "envguard"))

from attacks import build_attacks  # noqa: E402
from corpus import load_tasks  # noqa: E402
from sandbox import run_candidate  # noqa: E402

BASELINE_RESULTS = os.path.join(ROOT, "evaluation", "results", "v0.json")

# Phrases the baseline reaches for, mapped to the template that embodies them.
CLAIM_PATTERNS: list[tuple[str, str]] = [
    (r"input unchanged|returns? the input|unchanged", "identity"),
    (r"always returns? true|returns? true", "const_true"),
    (r"returns? none|none for all", "none"),
    (r"constant string|constant value like ['\"]|a constant string", "empty_str"),
    (r"empty list|returns? \[\]", "empty_list"),
    (r"hardcod", "hardcode_expected_0"),
    (r"constant", "const_int"),
]


def claimed_family(reason: str) -> str | None:
    lowered = reason.lower()
    for pattern, family in CLAIM_PATTERNS:
        if re.search(pattern, lowered):
            return family
    return None


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    if not os.path.exists(BASELINE_RESULTS):
        print("Run the baseline first:  python3 evaluation/run_eval.py --version v0", file=sys.stderr)
        return 2

    with open(BASELINE_RESULTS, "r", encoding="utf-8") as fh:
        baseline = json.load(fh)

    tasks = {t.id: t for t in load_tasks()}
    lines = [
        "# Refuting the baseline, by execution\n",
        "_Generated by `evaluation/refutations.py`. Do not edit by hand._\n",
        "\nThe baseline reads a verifier and judges it without running anything. It is\n"
        "never vague: every verdict comes with a specific, checkable reason. Each reason\n"
        "below is tested by executing a real program against the very verifier the\n"
        "baseline judged.\n",
    ]

    false_alarms = [r for r in baseline["rows"] if r["flagged"] and not r["truth_broken"]]

    refuted = 0
    considered = 0

    # --- direction 2: defects the baseline waved through ---------------------
    #
    # Which direction matters depends on how the baseline fails, and that is not
    # fixed. On a larger model it over-flagged and every sound environment drew a
    # false accusation; on this one it under-flags and misses real defects
    # instead. Only one of those two sections has rows at any given time, and
    # publishing whichever happens to be empty as though it proved something is
    # how an artefact ends up asserting "0 of 0 claims are false".
    missed = [r for r in baseline["rows"] if r["truth_broken"] and not r["flagged"]]
    if missed:
        lines.append("")
        lines.append("\n## Defects the baseline declared clean\n")
        lines.append(
            "\nThe baseline read each verifier and concluded it was sound. For each "
            "one below, a working exploit already exists in the corpus and is executed "
            "here against the very verifier the baseline cleared.\n"
        )
        lines.append("\n| Environment | The baseline's verdict | Exploit that beats it | Executed |")
        lines.append("|---|---|---|---|")
        for row in missed:
            task = tasks[row["task_id"]]
            exploit = task.reference_exploit
            if not exploit:
                continue
            result = run_candidate(task.verifier_src, exploit)
            considered += 1
            if result.passed:
                refuted += 1
            body = exploit.strip().splitlines()[-1].strip()
            reason = row["reason"].strip().rstrip(".")
            if len(reason) > 80:
                reason = reason[:77] + "..."
            lines.append(
                f"| `{task.id}` | \"{reason}\" | `{body}` | "
                f"{'**passes** (the verifier is broken)' if result.passed else 'fails'} |"
            )

    if false_alarms:
        lines.append("\n## Sound environments the baseline condemned\n")
        lines.append(
            "\nEach reason names a concrete program. That program is built and run here.\n"
        )
        lines.append("\n| Environment | The baseline's claim | Program it describes | Executed |")
        lines.append("|---|---|---|---|")

    for row in false_alarms:
        task = tasks[row["task_id"]]
        family = claimed_family(row["reason"])
        if family is None:
            continue

        attacks = {
            a.family: a
            for a in build_attacks(
                task.solution_src, task.verifier_src, task.entrypoints, task.entrypoint
            )
        }
        attack = attacks.get(family)
        if attack is None:
            continue

        considered += 1
        result = run_candidate(task.verifier_src, attack.source)
        verdict = "passes (claim holds)" if result.passed else f"**FAILS** ({result.summary()})"
        if not result.passed:
            refuted += 1

        body = attack.source.strip().splitlines()[-1].strip()
        claim = row["reason"].strip().rstrip(".")
        if len(claim) > 95:
            claim = claim[:92] + "..."
        lines.append(
            f"| `{task.id}` | {claim} | `{body}` | {verdict} |"
        )

    lines.append("")
    if considered == 0:
        lines.append(
            "\n_No checkable claims this run._ The baseline neither raised a false alarm "
            "on a sound environment nor cleared a defect for which a reference exploit "
            "exists, so there is nothing here to refute. Reported as empty rather than "
            "dressed up as a result.\n"
        )
    else:
        lines.append(
            f"\n**{refuted} of {considered}** checkable claims the baseline made are "
            "false, and each is refuted by executing a program against the very verifier "
            "the baseline judged.\n"
        )
        lines.append(
            "\nThe baseline is not vague. It is specific, confident, and wrong, which is "
            "the hardest kind of wrong to catch by reading.\n"
        )

    text = "\n".join(lines)
    print(text)
    if args.write:
        path = os.path.join(ROOT, "evaluation", "refutations.md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
